################################################################################
# main_script.R
#
# Main orchestration script for the simulation and evaluation workflow used in
# the RMutaPhy project.
#
# This script:
#   - loads all required functions,
#   - reads simulation parameters from a YAML configuration file,
#   - iterates over parameter combinations and numbers of tips,
#   - launches tree simulation and site-level analysis pipelines,
#   - saves all intermediate and final results to disk.
#
# The script is designed to ensure full reproducibility of the analyses by
# relying on a centralized configuration file and standardized output
# directories.
#
# Required inputs:
#   - R/functions.R
#   - analysis/simulation_evaluation/functions.R
#   - analysis/params.yml
#
# Outputs:
#   - Simulation results saved in the directory specified by params$output_dir
#   - HTML reports and intermediate objects generated by the pipeline scripts
#
# Usage:
#   source("analysis/simulation_evaluation/main_script.R")
#
################################################################################

# ---------------------------------------------------------------------------
# Load required functions
# ---------------------------------------------------------------------------

source(here::here("R/functions.R"))
source(here::here("analysis/simulation_evaluation/functions.R"))

# ---------------------------------------------------------------------------
# Load simulation parameters
# Each entry in params.yml corresponds to a simulation scenario
# ---------------------------------------------------------------------------

param_combinations <- yaml::read_yaml(here::here("analysis/params.yml"))

# ---------------------------------------------------------------------------
# Loop over simulation parameter combinations
# ---------------------------------------------------------------------------

for (params in param_combinations) {

  # Loop over different numbers of tips
  for (n_tip in params$n_tips) {
    params$n_tips <- n_tip

    # Create output directory if it does not exist
    output_dir <- here::here(params$output_dir)
    if (!dir.exists(output_dir)) {
      dir.create(output_dir, recursive = TRUE)
    }

    # Define output HTML report for the current simulation
    output_file <- here::here(sprintf("%s/outputs/pipeline_simulation_%dseqs.html",
                                      params$output_dir, params$n_tips))
    if (!dir.exists(dirname(output_file))) {
      dir.create(dirname(output_file), recursive = TRUE)
    }

    # -----------------------------------------------------------------------
    # Tree simulation and subtree detection pipeline
    # -----------------------------------------------------------------------
    source(here::here("analysis/simulation_evaluation/pipeline_simulation_trees.R"))

    # -----------------------------------------------------------------------
    # Site-level candidate detection pipeline
    # -----------------------------------------------------------------------
    source(here::here("analysis/simulation_evaluation/pipeline_sites.R"))

    # Log completion of the current simulation
    cat(sprintf("Simulation end for : %s and %d tips\n", params$output_dir, params$n_tips))
  }
}

